const cache = new Map<LangCode, TMap>([['en', en]]);

/** English is bundled; every other catalog is a separate chunk fetched on demand. */
export async function loadCatalog(lang: LangCode): Promise<TMap> {
  const hit = cache.get(lang);
  if (hit) return hit;
  const loader = LOADERS[lang as Exclude<LangCode, 'en'>];
  if (!loader) return en;
  const mod = await loader();
  cache.set(lang, mod.default);
  return mod.default;
}

/** Synchronously read a key, falling back to English for anything missing. */
export function t(catalog: TMap, key: TKey): string {
  return (catalog[key] ?? en[key]) as string;
}
